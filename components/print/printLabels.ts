export type Labels = Record<keyof (typeof labels)["en"], string>;

export function getLabels(lang: PrintLang): Labels {
  return labels[lang] as Labels;
}

export function fmtDate(ts: number | null | undefined, lang: PrintLang) {
  if (!ts) return "—";
  return new Date(ts).toLocaleDateString(lang === "ar" ? "ar-SA" : "en-GB", {
    day: "2-digit",
    month: "2-digit",
    year: "numeric",
  });
}

export function fmtNum(
  v: number | null | undefined,
  currencySymbol?: string | null,
) {
  if (v == null) return "—";
  const formatted = v.toLocaleString("en-US", {
    minimumFractionDigits: 2,
    maximumFractionDigits: 2,
  });
  return currencySymbol ? `${formatted} ${currencySymbol}` : formatted;
}
